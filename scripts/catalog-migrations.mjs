import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const destination = path.join(root, "worker/catalog-migrations.ts")

const names = readdirSync(path.join(root, "migrations"))
  .filter((name) => name.endsWith(".sql"))
  .sort()

const source = render(names)
const write = process.argv.includes("--write")

if (write) {
  writeFileSync(destination, source)
} else if (readFileSync(destination, "utf8") !== source) {
  console.error("worker/catalog-migrations.ts is missing a migration. Run: node scripts/catalog-migrations.mjs --write")
  process.exit(1)
}

function render(files) {
  const imports = files
    .map((name) => `import ${ident(name)} from "../migrations/${name}"`)
    .join("\n")
  const entries = files.map((name) => `  { name: "${name}", sql: ${ident(name)} },`).join("\n")
  return `// Generated by scripts/catalog-migrations.mjs. Do not edit.
import type { CatalogMigration } from "../server/catalog.ts"
${imports}

export const MIGRATIONS: CatalogMigration[] = [
${entries}
]
`
}

function ident(name) {
  return `sql_${name.replace(/[^a-zA-Z0-9]/g, "_")}`
}
